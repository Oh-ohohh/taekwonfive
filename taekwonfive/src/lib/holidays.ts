/** 공휴일이면 공휴일 이름, 토·일요일이면 "휴일", 평일이면 null.
 * 휴일에는 수업 대상이 없어 출석 체크가 필요 없지만, 출석한 학생은 추가할 수 있다. */
export function getDayOffLabel(date: string): string | null {
  return PUBLIC_HOLIDAYS[date] ?? (getCalendarWeekday(date) >= 6 ? "휴일" : null);
}

export function isDayOff(date: string): boolean {
  return getDayOffLabel(date) !== null;
}
